int get libraryExerciseCount =>
    exerciseLibraryGroups.fold(0, (sum, group) => sum + group.exercises.length);

List<LibraryExercise> buildDefaultExerciseLibrary() {
  final result = <LibraryExercise>[];
  for (final group in exerciseLibraryGroups) {
    for (var i = 0; i < group.exercises.length; i++) {
      result.add(LibraryExercise(
        id: 'builtin_${group.id}_$i',
        category: group.name,
        exercise: group.exercises[i],
        isBuiltIn: true,
      ));
    }
  }
  return result;
}
